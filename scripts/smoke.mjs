import { _electron as electron, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdtemp,mkdir,writeFile,access,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {readJSON} from '../core/storage.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const temporary=await mkdtemp(path.join(tmpdir(),'openvst-desktop-'));
const pluginDir=path.join(temporary,'plugins');
await mkdir(pluginDir);
await writeFile(path.join(temporary,'settings.json'),JSON.stringify({includePrereleases:false,paths:{VST3:pluginDir,AU:path.join(temporary,'components')}}));
const app=await electron.launch({args:[root],env:{...process.env,OPENVST_DATA_DIR:temporary},timeout:30000});
try{
 const page=await app.firstWindow();
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.getByRole('heading',{name:'Library',exact:true}).waitFor();
 await page.getByRole('button',{name:/openMaster Mastering/}).waitFor({timeout:90000});
 await mkdir(path.join(root,'docs','screenshots'),{recursive:true});
 await page.screenshot({path:path.join(root,'docs','screenshots','library.png')});
 for(const theme of ['Dark','Cyberpunk']){
   await page.getByRole('button',{name:theme,exact:true}).click();
   await expect(page.getByRole('button',{name:theme,exact:true})).toHaveAttribute('aria-pressed','true');
   await expect(page.locator('html')).toHaveAttribute('data-theme',theme.toLowerCase());
   await page.locator('.header-art').evaluate(image=>image.decode());
   await page.screenshot({path:path.join(root,'docs','screenshots',theme.toLowerCase()+'.png'),animations:'disabled'});
 }
 await page.reload();
 await page.getByRole('button',{name:/openMaster Mastering/}).waitFor({timeout:90000});
 assert.equal(await page.locator('html').getAttribute('data-theme'),'cyberpunk');
 await page.getByRole('button',{name:'Light',exact:true}).click();
 const initial=await page.evaluate(()=>window.manager.getState());
 const bundledCatalog=await readJSON(path.join(root,'catalog.json'));
 const {data:catalog}=await readJSON(path.join(temporary,'cache','catalog.json'),{data:bundledCatalog});
 assert.deepEqual(initial.plugins.map(plugin=>plugin.id).sort(),catalog.map(plugin=>plugin.id).sort());
 assert.equal(initial.settings.paths.VST3,pluginDir);
 await page.getByRole('textbox',{name:'Search plugins'}).fill('openMaster');
 await page.getByRole('button',{name:/openMaster Mastering/}).click();
 await page.getByLabel('Release',{exact:true}).selectOption('v1.0.0');
 await page.getByRole('button',{name:'Install plugin',exact:true}).click();
 await page.getByText('openMaster installed.',{exact:true}).waitFor({timeout:180000});

 let state=await page.evaluate(()=>window.manager.getState());
 const installed=state.plugins.find(p=>p.id==='openMaster').installed;
 assert.equal(installed.length,1);assert.equal(installed[0].managed,true);
 assert.equal(installed[0].version,'v1.0.0');
 await access(installed[0].path);
 const oldPath=installed[0].path;
 await page.getByRole('button',{name:/^Updates/}).click();
 await page.getByRole('button',{name:'Update all',exact:true}).click();
 await page.getByText('Your plugins are up to date.',{exact:true}).waitFor({timeout:180000});
 state=await page.evaluate(()=>window.manager.getState());
 const updated=state.plugins.find(p=>p.id==='openMaster').installed;
 assert.equal(updated[0].version,state.plugins.find(p=>p.id==='openMaster').releases[0].tag);
 assert.notEqual(updated[0].path,oldPath);
 await assert.rejects(()=>access(oldPath));
 await access(updated[0].path);
 const version=updated[0].version;
 await page.getByRole('button',{name:/^Installed/}).click();
 await page.screenshot({path:path.join(root,'docs','screenshots','installed.png')});
 await page.getByRole('button',{name:/Remove/}).click();
 await page.getByRole('dialog').getByRole('button',{name:/Remove/}).click();
 await page.getByText('openMaster removed.',{exact:true}).waitFor({timeout:30000});
 await assert.rejects(()=>access(updated[0].path));
 state=await page.evaluate(()=>window.manager.getState());assert.deepEqual(state.plugins.find(p=>p.id==='openMaster').installed,[]);
 assert.deepEqual(errors,[]);
 console.log(JSON.stringify({passed:true,platform:process.platform,version,plugins:initial.plugins.length,flow:'real legacy GitHub download → UI install → update all → renamed bundle migration → UI removal',screenshots:['docs/screenshots/library.png','docs/screenshots/installed.png']},null,2));
}catch(error){
 const page=await app.firstWindow();
 console.error((await page.locator('body').innerText()).slice(0,7000));
 throw error;
}finally{await app.close();await rm(temporary,{recursive:true,force:true});}
